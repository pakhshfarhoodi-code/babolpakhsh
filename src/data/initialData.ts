export const getRelativeJalaliDate = (daysAgo: number = 0, timeStr = '10:30') => {
  try {
    const d = new Date();
    d.setDate(d.getDate() - daysAgo);
    const parts = new Intl.DateTimeFormat('fa-IR-u-nu-latn', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    }).format(d);
    return `${parts} ${timeStr}`;
  } catch {
    return `1403/07/01 ${timeStr}`;
  }
};

